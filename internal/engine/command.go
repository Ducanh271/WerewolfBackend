package engine

// Command is a player's or the host's intent. Deciding a command never has
// side effects: it either returns the events it produces or an error.
type Command interface {
	isCommand()
}

// CommandMarker is embedded by every command, including the ones declared in
// the roles package, which cannot implement the unexported marker method on
// its own.
type CommandMarker struct{}

func (CommandMarker) isCommand() {}

// JoinRoom adds a player to the lobby. The room code is handled by the room
// layer; the engine only cares about the identity and the nickname.
type JoinRoom struct {
	CommandMarker
	Player   PlayerID
	Nickname string
}

// LeaveRoom removes a player from the lobby. It is only allowed before the
// deal; after it a player who is gone just stays disconnected and keeps the
// seat.
type LeaveRoom struct {
	CommandMarker
	Player PlayerID
}

// KickPlayer removes another player from the lobby, before the deal (audit
// K2). The room layer only ever builds this for the host; the engine does
// not check who sent it.
type KickPlayer struct {
	CommandMarker
	Target PlayerID
}

// SetSeats fixes the seating circle, clockwise. Order must list every player
// in the lobby exactly once. "Left" is index-1, wrapping.
type SetSeats struct {
	CommandMarker
	Order []PlayerID
}

// ConfigureRoles picks the role list for the game: how many players get each
// role. Picking CursedWolf is what selects the "Sói nguyền" option of the
// rules §2 table.
type ConfigureRoles struct {
	CommandMarker
	Roles map[RoleID]int
}

// DealRoles shuffles the configured roles over the seated players. Seed must
// be generated by the room layer with crypto/rand and never taken from a
// client; the same seed, seats and roles always give the same deal.
type DealRoles struct {
	CommandMarker
	Seed int64
}

// PhaseTimeout is sent by the room layer when a deadline passes. Phase and Seq
// are the ones the deadline was set for; a timeout that no longer matches the
// state is stale and ignored.
type PhaseTimeout struct {
	CommandMarker
	Phase Phase
	Seq   int
	// Seed settles an election that has no winner by votes (a tie, or nobody
	// voted). Like DealRoles, the room layer generates it with crypto/rand on
	// every timeout; it is never taken from a client. Other phases ignore it.
	Seed int64
	// DayClock marks the timeout of the 7-minute day clock rather than of the
	// phase's own timer. The day clock runs through the nomination countdown,
	// so in that phase the two need telling apart. The room layer sets it, with
	// the Seq the game has when the clock runs out.
	DayClock bool
}
