// gen-types writes the generated half of src/api/ from the server's contract
// (../docs/api/, CLAUDE.md "Hợp đồng trước, code sau"):
//
//   src/api/types.ts   TypeScript types of every message, from the three JSON
//                      Schemas: namespaces Server, Client and Http.
//   src/api/errors.ts  the sentence to show for every error code, read from
//                      the generated tables of ../docs/api/errors.md (there is
//                      no machine-readable file of them yet).
//
// Never edit those two files by hand: run `npm run gen:types`.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';
import { parseErrorTable } from './error-table.ts';

const web = join(dirname(fileURLToPath(import.meta.url)), '..');
const api = join(web, '..', 'docs', 'api');
const out = join(web, 'src', 'api');

const header = (from: string) =>
  `// GENERATED by \`npm run gen:types\` from ${from}. Do not edit.\n`;

async function schemaTypes(): Promise<string> {
  const parts: string[] = [header('../docs/api/schema/*.schema.json'), '/* eslint-disable */'];
  for (const [file, ns, root] of [
    ['server.schema.json', 'Server', 'ServerMessage'],
    ['client.schema.json', 'Client', 'ClientMessage'],
    ['http.schema.json', 'Http', 'HttpBody'],
  ] as const) {
    const schema = JSON.parse(readFileSync(join(api, 'schema', file), 'utf8'));
    delete schema.title; // the root type is named `root`, not after the title
    const ts = await compile(schema, root, {
      bannerComment: '',
      additionalProperties: false,
      strictIndexSignatures: true,
      unreachableDefinitions: true,
      format: true,
      style: { singleQuote: true },
    });
    parts.push(`/** ${file} */`, `export namespace ${ns} {`, indent(ts), '}');
  }
  return parts.join('\n') + '\n';
}

function indent(s: string): string {
  return s
    .trimEnd()
    .split('\n')
    .map((l) => (l ? '  ' + l : l))
    .join('\n');
}

function errorTexts(): string {
  const md = readFileSync(join(api, 'errors.md'), 'utf8');
  const table = parseErrorTable(md);
  return (
    header('../docs/api/errors.md (its generated tables)') +
    `import type { ErrorTable } from './error-table-type.ts';\n\n` +
    `/** The sentence to show for each error code (docs/api/errors.md "How to show an error"). */\n` +
    `export const errorTable: ErrorTable = ${JSON.stringify(table, null, 2)};\n`
  );
}

mkdirSync(out, { recursive: true });
writeFileSync(join(out, 'types.ts'), await schemaTypes());
writeFileSync(join(out, 'errors.ts'), errorTexts());
console.log('gen:types: src/api/types.ts, src/api/errors.ts');
